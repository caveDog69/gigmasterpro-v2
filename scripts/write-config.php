<?php
// Writes api/config.php from environment variables (used by the deploy workflow).
// Values are exported with var_export so secrets containing quotes or $ are written safely.
$env = static fn (string $k, string $d = '') => ($v = getenv($k)) === false || $v === '' ? $d : $v;
$required = ['GMP_DB_NAME', 'GMP_DB_USER', 'GMP_DB_PASS'];
foreach ($required as $k) {
    if ($env($k) === '') {
        fwrite(STDERR, "Missing required secret for {$k}\n");
        exit(1);
    }
}
$config = [
    'db_host' => $env('GMP_DB_HOST', 'localhost'),
    'db_port' => (int) $env('GMP_DB_PORT', '3306'),
    'db_name' => $env('GMP_DB_NAME'),
    'db_user' => $env('GMP_DB_USER'),
    'db_pass' => $env('GMP_DB_PASS'),
    'app_url' => rtrim($env('GMP_APP_URL'), '/'),
    'mail_from' => $env('GMP_MAIL_FROM'),
    'cors_origin' => $env('GMP_CORS_ORIGIN'),
    'debug' => false,
];
$out = $argv[1] ?? __DIR__ . '/../api/config.php';
file_put_contents($out, "<?php\n// Generated by the deploy workflow. Do not edit on the server; update GitHub secrets instead.\nreturn " . var_export($config, true) . ";\n");
echo "Wrote {$out}\n";
